#!/usr/bin/env bash
# Regenerates reference/assets.md from reference/assets/catalog.tsv and decal_flipbooks.tsv.
R="$(cd "$(dirname "$0")/../reference" && pwd)"
C="$R/assets/catalog.tsv"
{
echo "# Asset library (by asset id)"
echo
echo "This library holds every VFX texture and mesh the user has supplied, named by what it looks like (or by its role, when the author's emitter names say it), so it works without the source place open. Sources so far:"
echo
echo "- \`Workspace.modern_vfx\` (356 assets)"
echo "- \`Workspace.Effects\` (134 assets; entries prefixed \`Effects/\` in seen-in)"
echo "- \`Workspace[\"lightning stuff\"]\` (191 assets; prefixed \`lightning stuff/\`): lightning and electric sheets, about 50 lightning decals for meshes, spike and crater meshes"
echo
echo "Both are in PlaceId 114773467389373 and were added 2026-10-22. The machine-readable version is \`assets/catalog.tsv\`, and the 16-frame decal flipbooks are in \`assets/decal_flipbooks.tsv\`. The role guide is in \`textures.md\`. This file is regenerated by \`tools/build_assets_md.sh\`."
echo
echo "**Using an entry:**"
echo
echo "- Texture: \`rbxassetid://<id>\`."
echo "- Particle sheets: set \`FlipbookLayout\`/\`FlipbookMode\`/\`FlipbookFramerate\` from the catalog. A \`Custom\` layout can't be rebuilt from properties alone, so clone an emitter that already uses that id, or test it, then record the result here. With \`FlipbookMode=OneShot\` the sheet plays once over each particle's lifetime and the fps column doesn't matter. It only matters for Loop/PingPong/Random."
echo "- Meshes: \`mesh_native_size\` is \`MeshSize\` (X×Y×Z). For a SpecialMesh, \`Scale = desiredStuds / native\`. The flat or thin axis tells you how to orient it."
echo "- Prefixes: \`pe_\` particle, \`beam_\`/\`trail_\` strip textures (read along the length), \`decal_\` decals wrapped on meshes, \`mesh_\`, \`meshtex_\` MeshPart textures, \`image_\` screen-space ImageLabel."
echo "- Names ending \`_colored\` have color baked into the texture, so \`Color\` only tints them. Everything else is white or greyscale and takes its hue from \`Color\`. Blood sheets, for example, are white and tinted red."
echo "- **Never use \`pe_BLOCKED_moderated_circle\` (14687560696).** It's moderated and renders blank. Verify \`decal_UNAVAILABLE_placeholder\` (130540857336778) before using it, because its thumbnail is the unavailable placeholder."
echo "- Not catalogued on purpose: avatar clothing, hair and face meshes, weapon (blade, hilt, guard) meshes, camera props and UI counters."
echo
for k in Mesh Decal Beam Trail MeshTexture Image PE; do
  case $k in Mesh) t="Meshes";; Decal) t="Decals (decal-on-mesh)";; Beam) t="Beam textures";; Trail) t="Trail textures";; MeshTexture) t="MeshPart textures";; Image) t="Screen-space images";; PE) t="Particle textures";; esac
  echo "## $t"
  echo
  if [ $k = Mesh ]; then echo "| name | asset id | native size | uses | seen in |"; echo "|---|---|---|---|---|"; awk -F'\t' -v k=$k '$3==k {printf "| %s | %s | %s | %s | %s |\n", $2, $1, $9, $4, $10}' "$C"
  elif [ $k = PE ]; then echo "| name | asset id | layout | mode | fps | uses | seen in |"; echo "|---|---|---|---|---|---|---|"; awk -F'\t' -v k=$k '$3==k {printf "| %s | %s | %s | %s | %s | %s | %s |\n", $2, $1, $5, $6, $7, $4, $10}' "$C"
  else echo "| name | asset id | uses | seen in |"; echo "|---|---|---|---|"; awk -F'\t' -v k=$k '$3==k {printf "| %s | %s | %s | %s |\n", $2, $1, $4, $10}' "$C"; fi
  echo
done
echo "## 16-frame decal flipbooks"
echo
echo "Put these on a Decal over a SpecialMesh (Forge \`FlipbookEnabled\` + \`FlipbookTextures\`, or swap \`Decal.Texture\` across frames over the mesh's duration). The frame ids are listed in order in \`assets/decal_flipbooks.tsv\`."
echo
echo "| set | used on mesh | first frame |"
echo "|---|---|---|"
awk -F'\t' 'NR>1 {split($4,f,","); key=$4; if(!(key in seen)){seen[key]=1; printf "| %s.%s | %s | %s |\n", $1, $2, $3, f[1]}}' "$R/assets/decal_flipbooks.tsv"
} > "$R/assets.md"
echo "$(grep -c '^| [a-z]' "$R/assets.md") rows -> $R/assets.md"
